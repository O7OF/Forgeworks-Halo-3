class HaloTerrainGenerator:
    """Generates authentic, high-quality, realistic Halo BSP terrain using algorithms from BspTroubleShooting."""

    @staticmethod
    def calculate_mountain_profile(
        t_wall,
        cliff_steepness=2.2,
        cliff_height=850.0,
        mountain_height=None,
        crest_pos=0.80,
        shoulder_falloff=0.12,
        noise_val=0.0,
        strata_val=0.0,
        side_bias=1.0,
    ):
        """Calculates natural mountain wall elevation with an organic rounded ridge crest and
        summit shoulder roll-off. Eliminates sharp cutoffs and jagged sawteeth at the boundary rim."""
        t_c = min(1.0, max(0.0, t_wall))
        cp = max(0.50, min(0.95, crest_pos))
        sf = max(0.0, min(0.40, shoulder_falloff))

        if t_c <= cp:
            u = t_c / max(1e-4, cp)
            hermite = u * u * (3.0 - 2.0 * u)
            power = u ** cliff_steepness
            curve = power * (1.0 - hermite * 0.25) + (hermite * 0.25) * (u ** max(1.2, cliff_steepness * 0.7))
            noise_fade = 1.0 - 0.55 * (u ** 3)
            n_att = noise_val * noise_fade
            s_att = strata_val * noise_fade
        else:
            v = (t_c - cp) / max(1e-4, 1.0 - cp)
            drop = sf * (v * v * (3.0 - 2.0 * v))
            curve = 1.0 - drop
            noise_fade = max(0.12, 0.45 * (1.0 - v * 0.8))
            n_att = noise_val * noise_fade
            s_att = strata_val * noise_fade

        peak_h = mountain_height if mountain_height is not None else (cliff_height * 1.5)
        extra_h = max(0.0, peak_h - cliff_height)
        z_wall = (curve * cliff_height * side_bias) + (curve ** 2 * extra_h) + s_att + n_att
        return z_wall

    @staticmethod
    def generate_terrain(
        algorithm="HYBRID_ADVANCED",
        terrain_type=None,
        width=6000.0,
        length=12000.0,
        cliff_height=850.0,
        floor_flatness=0.35,
        cliff_steepness=2.2,
        meander_amount=0.15,
        noise_roughness=30.0,
        noise_scale=0.003,
        res_x=64,
        res_y=128,
        seal_mode="SEALED_ROOM",
        room_ceiling_z=1400.0,
        uv_scale=150.0,
        flip_uv_v=False,
        generate_water=True,
        water_level_z=0.0,
        terrain_shader="river riverworld_ground",
        cliff_shader="dead deadlock_cliff_rock",
        water_shader="river riverworld_water_rough'",
        water_depth=120.0,
        place_bases=False,
        horseshoe_passage="NATURAL_ARCH",
        generate_foliage=True,
        scatter_rocks=True,
        generate_portals=True,
        seed=1337,
        use_material_layering=True,
        shore_shader="mpshare mp_sand",
        mid_shader="out out_dirt",
        mid_slope_angle=20.0,
        cliff_slope_angle=45.0,
        topology_type="HEX_TRIANGULAR",
        mountain_height=None,
        mountain_ridge_sharpness=2.2,
        mountain_crest_rounding=0.80,
        crest_falloff=0.12,
        smooth_cliff_tops=True,
        erosion_iterations=12,
        domain_warp_strength=1.5,
        octaves=5,
        lacunarity=2.0,
        persistence=0.5,
        **kwargs
    ):
        """Generates realistic Halo BSP terrain utilizing procedural algorithms and physical erosion."""
        # Backward compatibility translation: if legacy terrain_type string passed, map to algorithmic params
        algo = algorithm
        legacy_name = "custom"
        if terrain_type is not None:
            legacy_name = str(terrain_type).lower()
            tt_up = str(terrain_type).upper()
            if "BLOOD_GULCH" in tt_up or "BATTLE_CREEK" in tt_up or "VALLEY" in tt_up:
                algo = "DOMAIN_WARP"
            elif "SNOWY" in tt_up or "ALPINE" in tt_up:
                algo = "RIDGED_MULTIFRACTAL"
            elif "DESERT" in tt_up or "MESA" in tt_up or "VOLCANIC" in tt_up:
                algo = "VORONOI_CELLULAR"
            elif "BADLANDS" in tt_up or "FORGE" in tt_up:
                algo = "HYBRID_ADVANCED"
            else:
                algo = "HYBRID_ADVANCED"
        elif algorithm:
            legacy_name = str(algorithm).lower()

        mesh_name = f"h3_terrain_{legacy_name}"
        mesh = bpy.data.meshes.new(mesh_name)
        bm = bmesh.new()

        W_half = width * 0.5
        L_half = length * 0.5
        seed_v = Vector((seed * 19.31, seed * 29.17, seed * 41.53))
        mountain_h = mountain_height if mountain_height is not None else (cliff_height * 1.5)

        # Scale resolution according to engine limits
        props = getattr(bpy.context.scene, "halo3_tool_props", None)
        game_key = getattr(props, "target_game", "HALO_3") if props else "HALO_3"
        game_preset = constants.HALO_GAME_PRESETS.get(game_key, constants.HALO_GAME_PRESETS["HALO_3"])
        max_faces_budget = game_preset.get("max_faces", 65536)

        est_faces = res_x * res_y * 2
        if est_faces > int(max_faces_budget * 0.70):
            target_faces = int(max_faces_budget * 0.65)
            scale_fac = math.sqrt(target_faces / max(1, est_faces))
            res_x = max(12, int(res_x * scale_fac))
            res_y = max(16, int(res_y * scale_fac))

        # Diamond-Square precalculation if selected
        ds_grid = None
        if algo == "DIAMOND_SQUARE":
            ds_grid = eval_diamond_square(res_x, res_y, roughness=persistence, seed=seed)

        # 1. Compute 2D elevation grid using mathematical algorithms
        grid_z = [[0.0 for _ in range(res_x)] for _ in range(res_y)]

        for iy in range(res_y):
            v_norm = (iy / max(1, res_y - 1)) - 0.5
            y = v_norm * length
            dy = y / L_half
            abs_dy = abs(dy)
            taper = math.cos(v_norm * math.pi)

            # Meandering valley spine
            if meander_amount > 0.0:
                x_center = (math.sin(v_norm * math.pi * 2.5) * 0.7 +
                            math.sin(v_norm * math.pi * 1.0) * 0.3) * (width * meander_amount) * taper
            else:
                x_center = 0.0

            y_straight = 0.55
            dy_end = 0.0 if abs_dy <= y_straight else (abs_dy - y_straight) / max(1e-4, 1.0 - y_straight)

            for ix in range(res_x):
                u_norm = (ix / max(1, res_x - 1)) - 0.5
                x = u_norm * width

                if x >= x_center:
                    dx = (x - x_center) / max(1.0, W_half - x_center)
                else:
                    dx = (x_center - x) / max(1.0, W_half + x_center)
                rel_dist = math.sqrt(dx * dx + dy_end * dy_end)

                p = Vector((x * noise_scale + seed_v.x, y * noise_scale + seed_v.y, 0.0))

                # --- Core Algorithm Evaluation ---
                if algo == "FBM_OCTAVES":
                    raw_elev = eval_fbm(p, octaves=octaves, lacunarity=lacunarity, gain=persistence) * noise_roughness
                elif algo == "DOMAIN_WARP":
                    raw_elev = eval_domain_warp(p, warp_strength=domain_warp_strength, octaves=octaves, lacunarity=lacunarity, gain=persistence) * noise_roughness * 1.2
                elif algo == "DIAMOND_SQUARE":
                    raw_elev = ds_grid[iy][ix] * (noise_roughness * 0.8)
                elif algo == "VORONOI_CELLULAR":
                    raw_elev = eval_voronoi_cellular(p, mode='CALDERA') * noise_roughness * 1.5
                elif algo == "RIDGED_MULTIFRACTAL":
                    raw_elev = eval_ridged_multifractal(p, octaves=octaves, lacunarity=lacunarity, gain=persistence, sharpness=mountain_ridge_sharpness) * (noise_roughness * 1.4)
                else:  # HYBRID_ADVANCED
                    base_warp = eval_domain_warp(p, warp_strength=domain_warp_strength, octaves=4, lacunarity=2.0, gain=0.5) * (noise_roughness * 0.7)
                    ridge_spine = eval_ridged_multifractal(p, octaves=4, lacunarity=2.0, gain=0.5, sharpness=2.2) * (noise_roughness * 0.5)
                    raw_elev = base_warp + ridge_spine

                if "FLATBOX_ISLAND" in tt_up:
                    plateau_limit = 1450.0
                    if abs(x) <= plateau_limit and abs(y) <= plateau_limit:
                        z = 35.0 + (raw_elev * 0.01)
                    else:
                        d_edge = max(abs(x) - plateau_limit, abs(y) - plateau_limit)
                        t_drop = min(1.0, d_edge / max(1.0, W_half - plateau_limit))
                        z = 35.0 - (t_drop * 65.0) + raw_elev
                elif "BIG_ISLAND" in tt_up or "ISLAND" in tt_up:
                    r_norm = math.hypot(x / W_half, y / L_half)
                    if r_norm < 0.45:
                        z = 80.0 + (1.0 - (r_norm / 0.45)) * cliff_height * 0.6 + raw_elev
                    else:
                        t_coast = min(1.0, (r_norm - 0.45) / 0.55)
                        z = 80.0 * (1.0 - t_coast) - 15.0 * t_coast + raw_elev
                elif rel_dist < floor_flatness:
                    # Organic playable floor with natural undulations
                    t_f = rel_dist / max(1e-4, floor_flatness)
                    floor_roll = math.cos(t_f * math.pi * 0.5) * 8.0
                    z = 10.0 + floor_roll + raw_elev
                else:
                    # Flanking mountain / canyon walls
                    t_cliff = min(1.0, (rel_dist - floor_flatness) / max(1e-4, 1.0 - floor_flatness))
                    strata = math.sin((y * 0.3 + cliff_height * 0.1) * 0.015) * (cliff_height * 0.04 * t_cliff)
                    z = 10.0 + raw_elev + HaloTerrainGenerator.calculate_mountain_profile(
                        t_wall=t_cliff,
                        cliff_steepness=cliff_steepness,
                        cliff_height=cliff_height,
                        mountain_height=mountain_h,
                        crest_pos=mountain_crest_rounding,
                        shoulder_falloff=crest_falloff,
                        noise_val=raw_elev * 0.8,
                        strata_val=strata
                    )

                grid_z[iy][ix] = z

        # 2. Physical Erosion Simulation Passes
        step_dx = width / max(1, res_x - 1)
        step_dy = length / max(1, res_y - 1)
        if erosion_iterations > 0 and "FLATBOX" not in tt_up:
            grid_z = simulate_hydraulic_erosion(
                grid_z, res_x, res_y,
                num_drops=min(5000, res_x * res_y * 2),
                rain_amount=0.5,
                sediment_capacity=0.8,
                evaporation_rate=0.08
            )
            grid_z = simulate_thermal_erosion(
                grid_z, step_dx, step_dy,
                repose_angle_deg=38.0,
                iterations=max(4, erosion_iterations // 2),
                talus_rate=0.35
            )

        # Foundation Pad Leveling for Bases
        if place_bases:
            red_y = -length * 0.36
            blue_y = length * 0.36
            pad_radius = 200.0
            blend_radius = 260.0
            for iy in range(res_y):
                v_norm = (iy / max(1, res_y - 1)) - 0.5
                y = v_norm * length
                for ix in range(res_x):
                    u_norm = (ix / max(1, res_x - 1)) - 0.5
                    x = u_norm * width
                    d_red = math.hypot(x, y - red_y)
                    d_blue = math.hypot(x, y - blue_y)
                    min_d = min(d_red, d_blue)
                    if min_d < pad_radius:
                        grid_z[iy][ix] = 0.0
                    elif min_d < blend_radius:
                        t = (min_d - pad_radius) / (blend_radius - pad_radius)
                        grid_z[iy][ix] *= (t * t * (3.0 - 2.0 * t))

        # 3. Build Mesh Vertices from Elevation Grid
        verts_grid = []
        for iy in range(res_y):
            row = []
            v_norm = (iy / max(1, res_y - 1)) - 0.5
            y = v_norm * length
            is_odd_row = (iy % 2 == 1) and (topology_type == "HEX_TRIANGULAR")
            x_row_offset = (0.5 * step_dx) if is_odd_row else 0.0

            for ix in range(res_x):
                u_norm = (ix / max(1, res_x - 1)) - 0.5
                x_raw = u_norm * width

                if topology_type == "HEX_TRIANGULAR":
                    if ix == 0:
                        x = -W_half
                    elif ix == res_x - 1:
                        x = W_half
                    else:
                        cliff_taper = 1.0 - max(0.0, min(1.0, (abs(u_norm) * 2.0 - floor_flatness) / max(0.1, 1.0 - floor_flatness))) * 0.70
                        x = x_raw + (x_row_offset * cliff_taper - 0.25 * step_dx * cliff_taper)
                else:
                    x = x_raw

                z = grid_z[iy][ix]
                if place_bases:
                    red_y = -length * 0.36
                    blue_y = length * 0.36
                    d_red = math.hypot(x, y - red_y)
                    d_blue = math.hypot(x, y - blue_y)
                    if min(d_red, d_blue) < 200.0:
                        z = 0.0

                v = bm.verts.new(Vector((x, y, z)))
                row.append(v)
            verts_grid.append(row)

        # 4. Construct Manifold Faces
        terrain_faces = []
        for iy in range(res_y - 1):
            for ix in range(res_x - 1):
                v00 = verts_grid[iy][ix]
                v10 = verts_grid[iy][ix + 1]
                v01 = verts_grid[iy + 1][ix]
                v11 = verts_grid[iy + 1][ix + 1]

                if topology_type == "HEX_TRIANGULAR":
                    if iy % 2 == 0:
                        f1 = bm.faces.new((v00, v10, v11))
                        f2 = bm.faces.new((v00, v11, v01))
                    else:
                        f1 = bm.faces.new((v00, v10, v01))
                        f2 = bm.faces.new((v10, v11, v01))
                else:
                    f1 = bm.faces.new((v00, v10, v11))
                    f2 = bm.faces.new((v00, v11, v01))

                terrain_faces.extend([f1, f2])

        # 5. Airtight Room Sealing (Satisfies Bungie Sealed World Rules per BspTroubleShooting)
        all_sky_faces = []
        all_block_faces = []
        if seal_mode == "SEALED_ROOM":
            z_ceil = max(room_ceiling_z, mountain_h + 300.0)
            boundary_verts = []
            for ix in range(res_x):
                boundary_verts.append(verts_grid[0][ix])
            for iy in range(1, res_y):
                boundary_verts.append(verts_grid[iy][res_x - 1])
            for ix in range(res_x - 2, -1, -1):
                boundary_verts.append(verts_grid[res_y - 1][ix])
            for iy in range(res_y - 2, 0, -1):
                boundary_verts.append(verts_grid[iy][0])

            n_b = len(boundary_verts)
            ceiling_verts = [bm.verts.new(Vector((v.co.x, v.co.y, z_ceil))) for v in boundary_verts]

            # Perimeter vertical wall faces linking terrain boundary to ceiling
            for i in range(n_b):
                next_i = (i + 1) % n_b
                f = bm.faces.new((boundary_verts[i], ceiling_verts[i], ceiling_verts[next_i], boundary_verts[next_i]))
                all_sky_faces.append(f)

            # Ceiling roof face
            f_ceil = bm.faces.new(list(reversed(ceiling_verts)))
            all_sky_faces.append(f_ceil)

            bmesh.ops.triangulate(bm, faces=all_sky_faces)
            all_sky_faces = [f for f in bm.faces if f not in terrain_faces]

        elif seal_mode == "SEALED_BLOCK":
            boundary_verts = []
            for ix in range(res_x):
                boundary_verts.append(verts_grid[0][ix])
            for iy in range(1, res_y):
                boundary_verts.append(verts_grid[iy][res_x - 1])
            for ix in range(res_x - 2, -1, -1):
                boundary_verts.append(verts_grid[res_y - 1][ix])
            for iy in range(res_y - 2, 0, -1):
                boundary_verts.append(verts_grid[iy][0])

            n_b = len(boundary_verts)
            min_z = min(v.co.z for row in verts_grid for v in row)
            z_base = min(min_z - 80.0, -100.0)

            base_verts = [bm.verts.new(Vector((v.co.x, v.co.y, z_base))) for v in boundary_verts]

            for i in range(n_b):
                next_i = (i + 1) % n_b
                f = bm.faces.new((boundary_verts[next_i], boundary_verts[i], base_verts[i], base_verts[next_i]))
                all_block_faces.append(f)

            # Flat bottom face closing the slab underneath
            f_bot = bm.faces.new(list(reversed(base_verts)))
            all_block_faces.append(f_bot)

            bmesh.ops.triangulate(bm, faces=all_block_faces)
            all_block_faces = [f for f in bm.faces if f not in terrain_faces]

        # 6. Apply Materials (Hermite Blending & Slope Aware)
        scene_props = getattr(bpy.context.scene, "halo3_tool_props", None) or getattr(bpy.context.scene, "halo3_terrain_tool", None)
        material_mode = kwargs.get("material_mode", None)
        if material_mode is None:
            if scene_props and getattr(scene_props, "terrain_material_mode", None) == "UNIFIED_BLENDED":
                material_mode = "UNIFIED_BLENDED"
            else:
                material_mode = "DISCRETE_SLOPES"

        mat_terrain = Halo3ShaderManager.get_or_create_material(terrain_shader)
        mat_cliff = Halo3ShaderManager.get_or_create_material(cliff_shader)
        mat_shore = Halo3ShaderManager.get_or_create_material(shore_shader)
        mat_mid = Halo3ShaderManager.get_or_create_material(mid_shader)
        mat_sky = Halo3ShaderManager.get_or_create_material("+sky")

        if material_mode == "UNIFIED_BLENDED":
            # In UNIFIED_BLENDED, Slot 0 = terrain, Slot 1 = cliff, Slot 2 = +sky
            for m in (mat_terrain, mat_cliff, mat_sky):
                if m.name not in [sm.name for sm in mesh.materials if sm]:
                    mesh.materials.append(m)
        else:
            for m in (mat_terrain, mat_cliff, mat_shore, mat_mid, mat_sky):
                if m.name not in [sm.name for sm in mesh.materials if sm]:
                    mesh.materials.append(m)

        idx_terrain = mesh.materials.find(mat_terrain.name)
        idx_cliff = mesh.materials.find(mat_cliff.name)
        idx_shore = mesh.materials.find(mat_shore.name) if mat_shore.name in mesh.materials else idx_terrain
        idx_mid = mesh.materials.find(mat_mid.name) if mat_mid.name in mesh.materials else idx_cliff
        idx_sky = mesh.materials.find(mat_sky.name)

        # Mark sky faces
        for f in all_sky_faces:
            f.material_index = idx_sky

        rad_mid = math.radians(mid_slope_angle)
        rad_cliff = math.radians(cliff_slope_angle)

        if material_mode == "UNIFIED_BLENDED":
            # All ground and block faces share material index 0 (single .shader_terrain)
            for f in all_block_faces:
                f.smooth = True
                f.material_index = 0
            for f in terrain_faces:
                f.smooth = True
                f.material_index = 0
        else:
            # Mark block faces
            for f in all_block_faces:
                f.smooth = True
                f.material_index = idx_cliff

            # Mark terrain faces based on physical slope angle and shore elevation
            for f in terrain_faces:
                f.smooth = True
                norm = f.normal
                nz = max(-1.0, min(1.0, norm.z))
                slope_rad = math.acos(abs(nz))
                avg_z = f.calc_center_median().z

                if avg_z <= water_level_z + 15.0 and slope_rad < rad_mid:
                    f.material_index = idx_shore
                elif slope_rad >= rad_cliff:
                    f.material_index = idx_cliff
                elif slope_rad >= rad_mid:
                    f.material_index = idx_mid
                else:
                    f.material_index = idx_terrain

        # 7. World UV Mapping & Engine Vertex Colors
        uv_layer_0 = bm.loops.layers.uv.new("UV_0")
        uv_layer_1 = bm.loops.layers.uv.new("UV_1") if material_mode == "UNIFIED_BLENDED" else None
        uv_layer_2 = bm.loops.layers.uv.new("UV_2") if material_mode == "UNIFIED_BLENDED" else None
        uv_layer_3 = bm.loops.layers.uv.new("UV_3") if material_mode == "UNIFIED_BLENDED" else None
        color_layer = bm.loops.layers.color.new("Terrain_Layers")

        for f in bm.faces:
            is_sky = (f.material_index == idx_sky)
            for loop in f.loops:
                co = loop.vert.co
                u = co.x / uv_scale
                v = (1.0 - (co.y / uv_scale)) if flip_uv_v else (co.y / uv_scale)
                loop[uv_layer_0].uv = Vector((u, v))
                if uv_layer_1 is not None:
                    loop[uv_layer_1].uv = Vector((u * 2.0, v * 2.0))
                    loop[uv_layer_2].uv = Vector((u * 4.0, v * 4.0))
                    loop[uv_layer_3].uv = Vector((u * 8.0, v * 8.0))

                if not is_sky:
                    nz = max(0.0, min(1.0, f.normal.z))
                    slope = math.acos(nz)
                    # Terrain_Layers: R=Ground, G=Cliff, B=Mid, A=Shore
                    r_w = max(0.0, 1.0 - (slope / max(1e-4, rad_cliff)))
                    g_w = min(1.0, slope / max(1e-4, rad_cliff))
                    loop[color_layer] = (r_w, g_w, 0.0, 1.0)

        # 8. Recalculate Normals per Bungie Inward Sealed World Rules
        if seal_mode == "SEALED_ROOM":
            bmesh.ops.recalc_face_normals(bm, faces=bm.faces[:])
            bmesh.ops.reverse_faces(bm, faces=bm.faces[:])
        else:
            bmesh.ops.recalc_face_normals(bm, faces=bm.faces[:])

        bm.to_mesh(mesh)
        bm.free()
        mesh.update()

        obj = bpy.data.objects.new(mesh_name, mesh)
        bpy.context.scene.collection.objects.link(obj)
        HaloCompiler.parent_to_level_root(obj)

        # 9. Ancillary Elements (Water Volume, Foliage, Rocks, Portals)
        is_island = "ISLAND" in tt_up
        if generate_water or is_island:
            try:
                water_name = "h3_island_ocean_water" if is_island else "h3_water_volume"
                w_w = max(width * 1.35, 4200.0) if is_island else width * 0.95
                w_l = max(length * 1.35, 4200.0) if is_island else length * 0.95
                w_obj = HaloWaterGenerator.generate_water(
                    water_type="SURFACE_RENDER",
                    width=w_w,
                    length=w_l,
                    water_level_z=water_level_z,
                    depth=water_depth,
                    water_shader=water_shader
                )
                if w_obj:
                    w_obj.name = water_name
            except Exception as e:
                print(f"[TERRAIN] Water generation notice: {e}")

        if generate_portals:
            try:
                HaloPortalGenerator.generate_portal(
                    width=width * 0.6,
                    height=cliff_height * 0.7,
                    y_pos=0.0
                )
            except Exception as e:
                print(f"[TERRAIN] Portal generation notice: {e}")

        if scatter_rocks:
            try:
                HaloRockGenerator.scatter_rocks_on_terrain(obj, passes=3, huge_count=2, med_count=6, small_count=14, micro_count=20, seed=seed)
            except Exception as e:
                print(f"[TERRAIN] Rock scattering notice: {e}")

        if generate_foliage:
            try:
                HaloFoliageGenerator.scatter_foliage_on_terrain(obj, count=36, seed=seed)
            except Exception as e:
                print(f"[TERRAIN] Foliage scattering notice: {e}")

        if place_bases:
            try:
                b_style = kwargs.get("bunker_ramp_style", "INTEGRATED")
                HaloBunkerGenerator.generate_bunker(
                    name="red_base_fortress",
                    loc_x=0.0,
                    loc_y=-length * 0.36,
                    loc_z=0.0,
                    rot_z=0.0,
                    ramp_style=b_style
                )
                HaloBunkerGenerator.generate_bunker(
                    name="blue_base_fortress",
                    loc_x=0.0,
                    loc_y=length * 0.36,
                    loc_z=0.0,
                    rot_z=math.pi,
                    ramp_style=b_style
                )
            except Exception as e:
                print(f"[TERRAIN] Base generation notice: {e}")

        return obj

    @staticmethod
    def apply_world_space_uvs(mesh_obj, uv_scale=150.0, flip_v=False):
        """Applies normal-aware, positive-winding world-space UVs to any mesh object."""
        if not mesh_obj or mesh_obj.type != 'MESH':
            return False
        mesh = mesh_obj.data
        uv_layer = mesh.uv_layers.get("UV_0") or mesh.uv_layers.new(name="UV_0")
        verts = mesh.vertices
        for poly in mesh.polygons:
            n = poly.normal
            nx, ny, nz = abs(n.x), abs(n.y), abs(n.z)
            for l_idx in poly.loop_indices:
                v_idx = mesh.loops[l_idx].vertex_index
                p = verts[v_idx].co
                if nz >= nx and nz >= ny:
                    if n.z >= 0.0:
                        u = p.x / uv_scale
                        v = p.y / uv_scale
                    else:
                        u = -p.x / uv_scale
                        v = p.y / uv_scale
                elif nx >= ny and nx >= nz:
                    if n.x >= 0.0:
                        u = p.y / uv_scale
                        v = p.z / uv_scale
                    else:
                        u = -p.y / uv_scale
                        v = p.z / uv_scale
                else:
                    if n.y >= 0.0:
                        u = -p.x / uv_scale
                        v = p.z / uv_scale
                    else:
                        u = p.x / uv_scale
                        v = p.z / uv_scale
                if flip_v:
                    v = 1.0 - v
                uv_layer.data[l_idx].uv = Vector((u, v))
        mesh.update()
        return True

    @staticmethod
    def fit_uv_to_01_box(mesh_obj, flip_v=False):
        """Fits UV coordinates exactly into [0.0, 1.0] bounding box without distortion."""
        if not mesh_obj or mesh_obj.type != 'MESH':
            return False, 0.0, 0.0
        mesh = mesh_obj.data
        uv_layer = mesh.uv_layers.get("UV_0") or mesh.uv_layers.new(name="UV_0")
        verts = mesh.vertices
        min_x = min(v.co.x for v in verts)
        max_x = max(v.co.x for v in verts)
        min_y = min(v.co.y for v in verts)
        max_y = max(v.co.y for v in verts)
        mesh_w = max(1e-4, max_x - min_x)
        mesh_h = max(1e-4, max_y - min_y)
        inv_w = 1.0 / mesh_w
        inv_h = 1.0 / mesh_h
        for poly in mesh.polygons:
            for l_idx in poly.loop_indices:
                v_idx = mesh.loops[l_idx].vertex_index
                p = verts[v_idx].co
                u = (p.x - min_x) * inv_w
                v = (1.0 - (p.y - min_y) * inv_h) if flip_v else ((p.y - min_y) * inv_h)
                uv_layer.data[l_idx].uv = Vector((u, v))
        mesh.update()
        return True, mesh_w, mesh_h

    fit_mesh_uvs_to_box = fit_uv_to_01_box

    @staticmethod
    def level_pad_under_base(terrain_obj, center=(0.0, 0.0), pad_size=400.0, pad_z=0.0):
        """Flattens and levels terrain mesh vertices directly beneath fortress and base foundations."""
        if not terrain_obj or terrain_obj.type != 'MESH':
            return False
        bm = bmesh.new()
        bm.from_mesh(terrain_obj.data)
        half_w = pad_size * 0.5
        cx, cy = center
        for v in bm.verts:
            if abs(v.co.x - cx) <= half_w and abs(v.co.y - cy) <= half_w:
                v.co.z = pad_z
        bm.to_mesh(terrain_obj.data)
        bm.free()
        terrain_obj.data.update()
        return True

    @staticmethod
    def seal_imported_mesh_as_terrain(
        mesh_obj,
        seal_mode="SEALED_ROOM",
        ceiling_z=650.0,
        base_z=-100.0,
        floor_shader="river riverworld_ground",
        cliff_shader="dead deadlock_cliff_rock",
        sky_shader="+sky",
        uv_scale=150.0
    ):
        """Converts any imported open terrain mesh into a 100% watertight sealed Halo BSP."""
        if not mesh_obj or mesh_obj.type != 'MESH':
            return False
        mesh = mesh_obj.data
        bm = bmesh.new()
        bm.from_mesh(mesh)
        bm.normal_update()

        b_edges = set(e for e in bm.edges if len(e.link_faces) == 1)
        if not b_edges:
            bm.to_mesh(mesh)
            bm.free()
            mesh.update()
            HaloTerrainGenerator.apply_world_space_uvs(mesh_obj, uv_scale=uv_scale)
            HaloBspDiagnostics.cleanup_mesh(mesh_obj, weld_dist=0.08, seal_open_edges=False)
            return True

        # Extract boundary loops
        loops = []
        while b_edges:
            adj = {}
            for e in b_edges:
                for v in e.verts:
                    adj.setdefault(v, []).append(e)
            if not adj:
                break
            start_v = next(iter(adj.keys()))
            curr_v = start_v
            loop = []
            visited_edges = set()
            while True:
                loop.append(curr_v)
                next_e = None
                for e in adj.get(curr_v, []):
                    if e in b_edges and e not in visited_edges:
                        next_e = e
                        break
                if not next_e:
                    break
                visited_edges.add(next_e)
                b_edges.remove(next_e)
                next_v = next_e.other_vert(curr_v)
                if next_v == start_v:
                    break
                curr_v = next_v
            if len(loop) >= 3:
                loops.append(loop)

        if not loops:
            bm.to_mesh(mesh)
            bm.free()
            return False

        def loop_bbox_size(lp):
            minx = min(v.co.x for v in lp)
            maxx = max(v.co.x for v in lp)
            miny = min(v.co.y for v in lp)
            maxy = max(v.co.y for v in lp)
            return (maxx - minx) ** 2 + (maxy - miny) ** 2

        loops.sort(key=loop_bbox_size, reverse=True)
        outer_loop = loops[0]

        mat_floor = Halo3ShaderManager.get_or_create_material(floor_shader)
        mat_cliff = Halo3ShaderManager.get_or_create_material(cliff_shader)
        mat_sky = Halo3ShaderManager.get_or_create_material(sky_shader)

        mat_names = [m.name for m in mesh.materials if m]
        for m in (mat_floor, mat_cliff, mat_sky):
            if m.name not in mat_names:
                mesh.materials.append(m)

        idx_floor = mesh.materials.find(mat_floor.name)
        idx_cliff = mesh.materials.find(mat_cliff.name)
        idx_sky = mesh.materials.find(mat_sky.name)

        for f in bm.faces:
            if f.material_index < 0 or f.material_index >= len(mesh.materials):
                f.material_index = idx_floor

        n = len(outer_loop)
        if seal_mode == "SEALED_ROOM":
            max_z = max(v.co.z for v in bm.verts)
            z_ceiling = max(ceiling_z, max_z + 150.0)
            ceil_verts = [bm.verts.new(Vector((v.co.x, v.co.y, z_ceiling))) for v in outer_loop]
            for i in range(n):
                next_i = (i + 1) % n
                v_bot1 = outer_loop[i]
                v_bot2 = outer_loop[next_i]
                v_top1 = ceil_verts[i]
                v_top2 = ceil_verts[next_i]
                f_sky = bm.faces.new((v_bot1, v_top1, v_top2, v_bot2))
                f_sky.material_index = idx_sky
            f_ceil = bm.faces.new(ceil_verts[::-1])
            f_ceil.material_index = idx_sky
        else:
            base_verts = [bm.verts.new(Vector((v.co.x, v.co.y, base_z))) for v in outer_loop]
            for i in range(n):
                next_i = (i + 1) % n
                v_top1 = outer_loop[i]
                v_top2 = outer_loop[next_i]
                v_bot1 = base_verts[i]
                v_bot2 = base_verts[next_i]
                f_skirt = bm.faces.new((v_top1, v_top2, v_bot2, v_bot1))
                f_skirt.material_index = idx_cliff
            f_base = bm.faces.new(base_verts[::-1])
            f_base.material_index = idx_cliff

        bmesh.ops.triangulate(bm, faces=bm.faces[:])
        if seal_mode == "SEALED_ROOM":
            bm.normal_update()
        else:
            bmesh.ops.recalc_face_normals(bm, faces=bm.faces[:])

        bm.to_mesh(mesh)
        bm.free()
        mesh.update()

        HaloTerrainGenerator.apply_world_space_uvs(mesh_obj, uv_scale=uv_scale)
        return True
