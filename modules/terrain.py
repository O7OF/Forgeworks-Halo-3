def eval_fbm(p, octaves=5, lacunarity=2.0, gain=0.5):
    """Fractal Brownian Motion (fBm): Layers multiple evaluations of gradient noise
    at increasing frequencies (lacunarity) and decreasing amplitudes (gain/persistence)."""
    total = 0.0
    freq = 1.0
    amp = 1.0
    max_amp = 0.0
    for _ in range(max(1, octaves)):
        v = p * freq
        total += noise.noise(v) * amp
        max_amp += amp
        freq *= lacunarity
        amp *= gain
    return total / max(1e-4, max_amp)


def eval_domain_warp(p, warp_strength=1.5, octaves=4, lacunarity=2.0, gain=0.5):
    """Domain Warping: Feeds the output of one noise function into the input coordinates of another:
    Height(p) = Noise(p + D(p)) where D(p) is generated by secondary noise vectors.
    Bends rigid symmetry into realistic winding river valleys, twisted ridges, and meanders."""
    q = Vector((
        eval_fbm(p + Vector((0.0, 0.0, 0.0)), octaves, lacunarity, gain),
        eval_fbm(p + Vector((5.2, 1.3, 2.8)), octaves, lacunarity, gain),
        eval_fbm(p + Vector((1.7, 9.2, 0.4)), octaves, lacunarity, gain),
    ))
    r = Vector((
        eval_fbm(p + warp_strength * q + Vector((1.7, 9.2, 0.15)), octaves, lacunarity, gain),
        eval_fbm(p + warp_strength * q + Vector((8.3, 2.8, 1.25)), octaves, lacunarity, gain),
        eval_fbm(p + warp_strength * q + Vector((2.1, 4.7, 7.3)), octaves, lacunarity, gain),
    ))
    return eval_fbm(p + warp_strength * r, octaves, lacunarity, gain)


def eval_diamond_square(res_x, res_y, roughness=0.55, seed=1337):
    """Midpoint Displacement / Diamond-Square Algorithm: Recursive fractal subdivision on a 2D grid.
    Generates craggy, fractured mountains and rugged alpine topography."""
    # Find smallest power-of-two grid size >= max(res_x, res_y)
    max_dim = max(res_x, res_y)
    n = 1
    while n < max_dim - 1:
        n *= 2
    size = n + 1

    grid = [[0.0 for _ in range(size)] for _ in range(size)]
    rng = random.Random(seed)

    # Initialise corners
    grid[0][0] = rng.uniform(-1.0, 1.0)
    grid[0][n] = rng.uniform(-1.0, 1.0)
    grid[n][0] = rng.uniform(-1.0, 1.0)
    grid[n][n] = rng.uniform(-1.0, 1.0)

    step = n
    scale = 1.0

    while step > 1:
        half = step // 2

        # Diamond step
        for y in range(half, n, step):
            for x in range(half, n, step):
                avg = (grid[y - half][x - half] + grid[y - half][x + half] +
                       grid[y + half][x - half] + grid[y + half][x + half]) * 0.25
                grid[y][x] = avg + rng.uniform(-scale, scale)

        # Square step
        for y in range(0, size, half):
            shift = 0 if (y // half) % 2 == 1 else half
            for x in range(shift, size, step):
                total = 0.0
                count = 0
                if y >= half:
                    total += grid[y - half][x]
                    count += 1
                if y + half < size:
                    total += grid[y + half][x]
                    count += 1
                if x >= half:
                    total += grid[y][x - half]
                    count += 1
                if x + half < size:
                    total += grid[y][x + half]
                    count += 1
                grid[y][x] = (total / count) + rng.uniform(-scale, scale)

        step //= 2
        scale *= roughness

    # Resample grid down to target res_x, res_y
    res = [[0.0 for _ in range(res_x)] for _ in range(res_y)]
    for iy in range(res_y):
        sy = (iy / max(1, res_y - 1)) * n
        y0 = int(sy)
        y1 = min(n, y0 + 1)
        fy = sy - y0
        for ix in range(res_x):
            sx = (ix / max(1, res_x - 1)) * n
            x0 = int(sx)
            x1 = min(n, x0 + 1)
            fx = sx - x0
            top = grid[y0][x0] * (1.0 - fx) + grid[y0][x1] * fx
            bot = grid[y1][x0] * (1.0 - fx) + grid[y1][x1] * fx
            res[iy][ix] = top * (1.0 - fy) + bot * fy

    return res


def eval_voronoi_cellular(p, mode='CELLULAR'):
    """Voronoi / Worley Noise: Distance to feature points generating volcanic calderas,
    cracked desert basins, mesas, and basalt columns."""
    dist_v1 = noise.noise_vector(p, 'VORONOI_F1')
    dist_v2 = noise.noise_vector(p, 'VORONOI_F2')
    d1 = dist_v1.length
    d2 = dist_v2.length

    if mode == 'BASALT_TERRACE':
        # Stepped columnar terrace
        steps = 4.0
        val = (d2 - d1) * 2.0
        return math.floor(val * steps) / steps
    elif mode == 'CRACKED_BASIN':
        # Cracked canyons along cell boundaries
        edge = d2 - d1
        return min(1.0, edge * 3.5)
    else:  # CALDERA / MESA
        # Flat topped mesa with steep falls
        v = 1.0 - min(1.0, d1 * 1.5)
        return v * v * (3.0 - 2.0 * v)


def eval_ridged_multifractal(p, octaves=5, lacunarity=2.0, gain=0.5, sharpness=2.0):
    """Ridged Multifractal: Inverted absolute noise producing razorback mountain crests,
    alpine arêtes, and jagged spines."""
    total = 0.0
    freq = 1.0
    amp = 1.0
    weight = 1.0
    for _ in range(max(1, octaves)):
        signal = 1.0 - abs(noise.noise(p * freq))
        signal = signal ** sharpness
        signal *= weight
        weight = max(0.0, min(1.0, signal * 2.0))
        total += signal * amp
        freq *= lacunarity
        amp *= gain
    return total


