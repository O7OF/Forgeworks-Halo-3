def simulate_thermal_erosion(grid_z, dx, dy, repose_angle_deg=35.0, iterations=8, talus_rate=0.35):
    """Thermal Erosion: Simulates gravity rockfall and weathering. When the slope between
    adjacent grid cells exceeds the angle of repose, material shifts from higher to lower cell,
    forming realistic talus scree aprons and natural cliff bases."""
    res_y = len(grid_z)
    res_x = len(grid_z[0])
    tan_repose = math.tan(math.radians(repose_angle_deg))
    talus_limit_x = dx * tan_repose
    talus_limit_y = dy * tan_repose

    for _ in range(iterations):
        for iy in range(1, res_y - 1):
            for ix in range(1, res_x - 1):
                z = grid_z[iy][ix]
                # Compare to 4 neighbors
                neighbors = [
                    (iy, ix + 1, talus_limit_x),
                    (iy, ix - 1, talus_limit_x),
                    (iy + 1, ix, talus_limit_y),
                    (iy - 1, ix, talus_limit_y),
                ]
                for ny, nx, limit in neighbors:
                    diff = z - grid_z[ny][nx]
                    if diff > limit:
                        excess = (diff - limit) * talus_rate * 0.25
                        grid_z[iy][ix] -= excess
                        grid_z[ny][nx] += excess
    return grid_z


def simulate_hydraulic_erosion(grid_z, res_x, res_y, num_drops=3000, rain_amount=0.5, sediment_capacity=0.8, evaporation_rate=0.08):
    """Hydraulic Erosion: Simulates rainfall runoff using particle fluid dynamics.
    Virtual raindrops land on heightmap, flow downhill along height gradient, carve natural
    river tributaries/drainage basins, deposit sediment in alluvial depressions, and evaporate."""
    rng = random.Random(42)
    for _ in range(num_drops):
        px = rng.uniform(1, res_x - 2)
        py = rng.uniform(1, res_y - 2)
        water = rain_amount
        sediment = 0.0
        vx = 0.0
        vy = 0.0

        for _ in range(25):  # Max raindrop lifetime
            ix = int(px)
            iy = int(py)
            if ix < 1 or ix >= res_x - 2 or iy < 1 or iy >= res_y - 2:
                break

            # Compute height gradient
            gx = (grid_z[iy][ix + 1] - grid_z[iy][ix - 1]) * 0.5
            gy = (grid_z[iy + 1][ix] - grid_z[iy - 1][ix]) * 0.5

            vx = vx * 0.5 - gx * 0.5
            vy = vy * 0.5 - gy * 0.5
            speed = math.sqrt(vx * vx + vy * vy)
            if speed < 1e-4:
                break

            px += vx / speed
            py += vy / speed

            nix = int(px)
            niy = int(py)
            if nix < 1 or nix >= res_x - 2 or niy < 1 or niy >= res_y - 2:
                break

            height_diff = grid_z[iy][ix] - grid_z[niy][nix]
            capacity = max(0.0, height_diff) * speed * water * sediment_capacity

            if sediment > capacity or height_diff < 0.0:
                # Deposit sediment
                deposit = (sediment - capacity) * 0.5 if height_diff > 0.0 else min(sediment, -height_diff)
                grid_z[iy][ix] += deposit
                sediment -= deposit
            else:
                # Erode sediment
                erode = min((capacity - sediment) * 0.3, height_diff)
                grid_z[iy][ix] -= erode
                sediment += erode

            water *= (1.0 - evaporation_rate)
            if water < 0.02:
                break
    return grid_z


